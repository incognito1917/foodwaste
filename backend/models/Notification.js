const mongoose = require('mongoose');

const notificationSchema = new mongoose.Schema(
  {
    userId: {
      type: mongoose.Schema.Types.ObjectId,
      ref: 'User',
      required: true,
    },
    message: {
      type: String,
      required: true,
    },
    type: {
      type: String,
      enum: ['DONATION_ACCEPTED', 'PICKUP_ASSIGNED', 'FOOD_PICKED_UP', 'FOOD_DELIVERED', 'EXPIRY_WARNING', 'SYSTEM'],
      default: 'SYSTEM',
    },
    link: {
      type: String,
      default: '',
    },
    isRead: {
      type: Boolean,
      default: false,
    },
  },
  {
    timestamps: true,
  }
);

module.exports = mongoose.model('Notification', notificationSchema);
